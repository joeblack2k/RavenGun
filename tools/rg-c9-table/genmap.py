#!/usr/bin/env python3
"""Generate tools/rg-c9table/rg_c9_map.h: the XP address -> API name map of Coopers's 9's own call table.

Coopers's 9's game.exe is a flat memory image (file offset == RVA; tools/dev/pe-flat-fix.py repairs its section table),
so every slot of its import table holds the address that API had on the machine the dump was taken from (Windows XP).
The import descriptors still carry the names, so pairing slot -> name gives the map without asking Windows XP anything.

Usage: genmap.py <game.exe> <fixed.exe> [--ref DLLNAME=path]... > rg_c9_map.h
      (fixed.exe = the output of tools/dev/pe-flat-fix.py for the same file)

--ref MSVCR71.dll=/path/to/msvcr71.dll adds every export of a reference copy of that DLL (address = its preferred
ImageBase + export RVA), but only when that copy is the build the dump's machine had: every address the dump's own
import table names for that DLL must come out of the reference with the same name, otherwise the reference is refused.
Coopers's 9's call table holds 64 msvcr71 slots of which the import table names one (__dllonexit); the msvcr71.dll
7.10.7031.4 that other games ship (preferred base 0x7C360000) reproduces it and names all 64. The reference is only
read; nothing of it goes into the repo except the export names it confirms.
"""
import struct
import sys

import pefile

args = sys.argv[1:]
refs = []
while '--ref' in args:
    i = args.index('--ref')
    refs.append(args[i + 1].split('=', 1))
    del args[i:i + 2]
if len(args) < 2:
    sys.exit(__doc__)
RAW, FLAT = args[0], args[1]

pe = pefile.PE(FLAT, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_IMPORT']])
base = pe.OPTIONAL_HEADER.ImageBase
raw = open(RAW, 'rb').read()

rows = {}
for d in pe.DIRECTORY_ENTRY_IMPORT:
    dll = d.dll.decode('latin1')
    for imp in d.imports:
        slot = imp.address - base                      # flat image: file offset == RVA
        value = struct.unpack_from('<I', raw, slot)[0]
        if value in rows:
            continue
        if imp.name:
            rows[value] = (dll, imp.name.decode('latin1'), 0)
        else:
            rows[value] = (dll, '', imp.ordinal)

for dll, path in refs:
    ref = pefile.PE(path, fast_load=True)
    ref.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
    rbase = ref.OPTIONAL_HEADER.ImageBase
    exports = {}
    for e in ref.DIRECTORY_ENTRY_EXPORT.symbols:
        if e.address and e.name:
            exports.setdefault(rbase + e.address, e.name.decode('latin1'))
    anchors = [(xp, row[1]) for xp, row in rows.items() if row[0].lower() == dll.lower() and row[1]]
    bad = [(hex(xp), name, exports.get(xp)) for xp, name in anchors if exports.get(xp) != name]
    if not anchors or bad:
        sys.exit('reference %s for %s refused: anchors %d, mismatches %s' % (path, dll, len(anchors), bad))
    added = 0
    for xp, name in exports.items():
        if xp not in rows:
            rows[xp] = (dll, name, 0)
            added += 1
    print('/* %s: %d anchors match, %d exports added */' % (dll, len(anchors), added), file=sys.stderr)

print("""/* Generated by tools/rg-c9-table/genmap.py from game.exe's own import descriptors: the dump is a flat memory image, so
 * every import slot holds the address that API had on the machine the dump came from (Windows XP). Pairing slot and
 * name gives this map without asking Windows XP anything. A --ref DLL adds the exports of a reference copy whose
 * build reproduces every address the import table names for it. Sorted by address (bsearch). Do not edit by hand. */
static const struct rg_xp_map {
    unsigned long xp;
    const char *dll;
    const char *name;      /* empty: imported by ordinal */
    unsigned short ordinal;
} k_xp_map[] = {""")
for xp in sorted(rows):
    dll, name, ordinal = rows[xp]
    print('    {0x%08xul, "%s", "%s", %d},' % (xp, dll, name, ordinal))
print('};')
print('#define RG_XP_MAP_N (sizeof k_xp_map / sizeof k_xp_map[0])')
print('/* %d addresses */' % len(rows), file=sys.stderr)
