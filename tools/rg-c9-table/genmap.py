#!/usr/bin/env python3
"""Generate tools/rg-c9table/rg_c9_map.h: the XP address -> API name map of Coopers's 9's own call table.

Coopers's 9's game.exe is a flat memory image (file offset == RVA; tools/dev/pe-flat-fix.py repairs its section table),
so every slot of its import table holds the address that API had on the machine the dump was taken from (Windows XP).
The import descriptors still carry the names, so pairing slot -> name gives the map without asking Windows XP anything.

Usage: genmap.py <game.exe> <fixed.exe> > rg_c9_map.h
      (fixed.exe = the output of tools/dev/pe-flat-fix.py for the same file)
"""
import struct
import sys

import pefile

if len(sys.argv) < 3:
    sys.exit(__doc__)
RAW, FLAT = sys.argv[1], sys.argv[2]

pe = pefile.PE(FLAT, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_IMPORT']])
base = pe.OPTIONAL_HEADER.ImageBase
raw = open(RAW, 'rb').read()

rows = {}
for d in pe.DIRECTORY_ENTRY_IMPORT:
    dll = d.dll.decode('latin1')
    for imp in d.imports:
        slot = imp.address - base                      # flat image: file offset == RVA
        value = struct.unpack_from('<I', raw, slot)[0]
        if value in rows:
            continue
        if imp.name:
            rows[value] = (dll, imp.name.decode('latin1'), 0)
        else:
            rows[value] = (dll, '', imp.ordinal)

print("""/* Generated by tools/rg-c9-table/genmap.py from game.exe's own import descriptors: the dump is a flat memory image, so
 * every import slot holds the address that API had on the machine the dump came from (Windows XP). Pairing slot and
 * name gives this map without asking Windows XP anything. Do not edit by hand. */
static const struct rg_xp_map {
    unsigned long xp;
    const char *dll;
    const char *name;      /* empty: imported by ordinal */
    unsigned short ordinal;
} k_xp_map[] = {""")
for xp in sorted(rows):
    dll, name, ordinal = rows[xp]
    print('    {0x%08xul, "%s", "%s", %d},' % (xp, dll, name, ordinal))
print('};')
print('#define RG_XP_MAP_N (sizeof k_xp_map / sizeof k_xp_map[0])')
print('/* %d addresses */' % len(rows), file=sys.stderr)
